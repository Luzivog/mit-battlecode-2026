package bcx.tr;

import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.tree.*;

import java.util.*;

/** A class of a module, with the JVM's resolution and selection rules (JVMS 5.4.3, 5.4.6). */
public final class Cls {
    public final Pool pool;
    public final Pool.Module mod;
    public final String name;
    public final ClassNode node;
    public final String cname;
    public final Map<String, Mth> methods = new LinkedHashMap<>();
    public final Map<String, Fld> fields = new LinkedHashMap<>();
    private Cls superCls;
    private List<Cls> ifaces;
    private boolean linked;

    // RTA state
    public boolean instantiated;
    public boolean initReachable;   // <clinit> chain may run
    public boolean mirrorNeeded;
    public int id = -1;             // dense index among emitted classes
    public int initIndex = -1;      // index into the module's init-state table (if it has init work)

    // layout
    public List<Mth> vtable;
    public Map<Cls, Mth[]> itables;
    public List<Fld> staticFields;

    /** Synthetic class: generated by the translator, not loaded. */
    public final boolean synthetic;

    Cls(Pool pool, Pool.Module mod, String name, ClassNode node) {
        this(pool, mod, name, node, false);
    }

    Cls(Pool pool, Pool.Module mod, String name, ClassNode node, boolean synthetic) {
        this.pool = pool;
        this.mod = mod;
        this.name = name;
        this.node = node;
        this.synthetic = synthetic;
        this.cname = "c" + mod.index + "_" + Names.mangle(name);
        for (MethodNode m : node.methods) methods.put(m.name + m.desc, new Mth(this, m));
        for (FieldNode f : node.fields) fields.put(f.name, new Fld(this, f));
    }

    public boolean isInterface() { return (node.access & Opcodes.ACC_INTERFACE) != 0; }
    public boolean isAbstract() { return (node.access & Opcodes.ACC_ABSTRACT) != 0; }
    public boolean isFinal() { return (node.access & Opcodes.ACC_FINAL) != 0; }
    public String pkg() { int i = name.lastIndexOf('/'); return i < 0 ? "" : name.substring(0, i); }

    public Cls superCls() { link(); return superCls; }
    public List<Cls> interfaces() { link(); return ifaces; }

    private void link() {
        if (linked) return;
        Cls s = node.superName == null ? null : pool.ref(mod, node.superName);
        List<Cls> is = new ArrayList<>();
        for (String i : node.interfaces) is.add(pool.ref(mod, i));
        superCls = s;
        ifaces = is;
        linked = true;
    }

    public boolean isSubclassOf(Cls t) {
        for (Cls c = this; c != null; c = c.superCls()) if (c == t) return true;
        return false;
    }

    /** All superinterfaces, transitively, each once, in a stable order. */
    public LinkedHashSet<Cls> allInterfaces() {
        LinkedHashSet<Cls> out = new LinkedHashSet<>();
        for (Cls c = this; c != null; c = c.superCls()) collectIfaces(c, out);
        return out;
    }

    private static void collectIfaces(Cls c, LinkedHashSet<Cls> out) {
        for (Cls i : c.interfaces()) if (out.add(i)) collectIfaces(i, out);
    }

    public boolean isSubtypeOf(Cls t) {
        if (t.isInterface()) return this == t || allInterfaces().contains(t);
        return isSubclassOf(t);
    }

    public Mth own(String name, String desc) { return methods.get(name + desc); }

    // ---- field resolution (JVMS 5.4.3.2)
    public Fld resolveField(String name, String desc) {
        Fld f = fields.get(name);
        if (f != null && f.desc.equals(desc)) return f;
        for (Cls i : interfaces()) {
            Fld r = i.resolveField(name, desc);
            if (r != null) return r;
        }
        Cls s = superCls();
        return s == null ? null : s.resolveField(name, desc);
    }

    // ---- method resolution (JVMS 5.4.3.3, 5.4.3.4)
    public Mth resolveMethod(String name, String desc, boolean itf) {
        if (itf) {
            Mth m = own(name, desc);
            if (m != null) return m;
            Cls obj = pool.get(pool.sys, "java/lang/Object");
            Mth om = obj.own(name, desc);
            if (om != null && (om.node.access & Opcodes.ACC_PUBLIC) != 0 && !om.isStatic()) return om;
            return maximallySpecific(name, desc, true);
        }
        for (Cls c = this; c != null; c = c.superCls()) {
            Mth m = c.own(name, desc);
            if (m != null) return m;
            if (c.isSignaturePolymorphic(name)) return c.own(name, "([Ljava/lang/Object;)Ljava/lang/Object;");
        }
        return maximallySpecific(name, desc, true);
    }

    private boolean isSignaturePolymorphic(String n) {
        return name.equals("java/lang/invoke/MethodHandle") || name.equals("java/lang/invoke/VarHandle");
    }

    /** Maximally-specific superinterface methods; prefers a single non-abstract one. */
    public Mth maximallySpecific(String name, String desc, boolean allowAbstract) {
        List<Mth> cands = new ArrayList<>();
        for (Cls i : allInterfaces()) {
            Mth m = i.own(name, desc);
            if (m == null || m.isStatic() || (m.node.access & Opcodes.ACC_PRIVATE) != 0) continue;
            cands.add(m);
        }
        // keep the maximally specific ones
        List<Mth> max = new ArrayList<>();
        for (Mth m : cands) {
            boolean dominated = false;
            for (Mth o : cands)
                if (o != m && o.owner != m.owner && o.owner.isSubtypeOf(m.owner)) { dominated = true; break; }
            if (!dominated) max.add(m);
        }
        Mth concrete = null;
        int nConcrete = 0;
        for (Mth m : max) if (!m.isAbstract()) { concrete = m; nConcrete++; }
        if (nConcrete == 1) return concrete;
        if (nConcrete > 1) return null; // IncompatibleClassChangeError at run time
        if (allowAbstract && !max.isEmpty()) return max.get(0);
        return null;
    }

    /** Selection for invokevirtual / invokeinterface on an object of this class (JVMS 5.4.6). */
    public Mth select(Mth resolved) {
        if ((resolved.node.access & Opcodes.ACC_PRIVATE) != 0) return resolved;
        for (Cls c = this; c != null; c = c.superCls()) {
            Mth m = c.own(resolved.name, resolved.desc);
            if (m != null && !m.isStatic() && overrides(m, resolved)) return m;
        }
        Mth d = maximallySpecific(resolved.name, resolved.desc, false);
        return d;
    }

    /** Does m (declared in a subclass or the same class) override r? */
    static boolean overrides(Mth m, Mth r) {
        if (m == r) return true;
        if ((m.node.access & Opcodes.ACC_PRIVATE) != 0) return false;
        int ra = r.node.access;
        if ((ra & (Opcodes.ACC_PUBLIC | Opcodes.ACC_PROTECTED)) != 0) return true;
        if ((ra & Opcodes.ACC_PRIVATE) != 0) return false;
        // package-private: same runtime package
        if (m.owner.mod == r.owner.mod && m.owner.pkg().equals(r.owner.pkg())) return true;
        // or m overrides some m' in between that overrides r
        for (Cls c = m.owner.superCls(); c != null && c != r.owner; c = c.superCls()) {
            Mth mid = c.own(m.name, m.desc);
            if (mid != null && mid != m && overrides(m, mid) && overrides(mid, r)) return true;
        }
        return false;
    }

    public String toString() { return mod + ":" + name; }

    public static final class Mth {
        public final Cls owner;
        public final MethodNode node;
        public final String name, desc;
        public final String cname;
        public boolean reachable;
        public boolean emitted;
        public String nativeImpl;       // C++ function implementing a native/substituted method
        public boolean nothrow;         // the native never leaves an exception pending
        public int vslot = -1;
        public Mth from;               // the method that first made this one reachable (for reports)
        Mth(Cls owner, MethodNode node) {
            this.owner = owner;
            this.node = node;
            this.name = node.name;
            this.desc = node.desc;
            this.cname = owner.cname + "__" + Names.mangle(name) + "_" + Names.descHash(desc);
        }
        public boolean isStatic() { return (node.access & Opcodes.ACC_STATIC) != 0; }
        public boolean isAbstract() { return (node.access & Opcodes.ACC_ABSTRACT) != 0; }
        public boolean isNative() { return (node.access & Opcodes.ACC_NATIVE) != 0; }
        public boolean isPrivate() { return (node.access & Opcodes.ACC_PRIVATE) != 0; }
        public boolean isFinal() { return (node.access & Opcodes.ACC_FINAL) != 0; }
        public Type[] args() { return Type.getArgumentTypes(desc); }
        public Type ret() { return Type.getReturnType(desc); }
        public String toString() { return owner + "." + name + desc; }
    }

    public static final class Fld {
        public final Cls owner;
        public final FieldNode node;
        public final String name, desc;
        public final String cname;
        Fld(Cls owner, FieldNode node) {
            this.owner = owner;
            this.node = node;
            this.name = node.name;
            this.desc = node.desc;
            this.cname = "f_" + Names.mangle(name);
        }
        public boolean isStatic() { return (node.access & Opcodes.ACC_STATIC) != 0; }
        public String toString() { return owner + "." + name; }
    }
}

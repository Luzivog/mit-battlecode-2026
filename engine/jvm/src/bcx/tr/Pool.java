package bcx.tr;

import battlecode.instrumenter.TeamClassLoaderFactory;
import battlecode.server.Config;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.*;

import java.io.InputStream;
import java.util.*;

/**
 * Where classes come from. A module is the system (the engine, the JDK, our driver: one copy, global statics) or a
 * team (its classes as the official instrumenter rewrites them, its instrumented JDK copies and the engine's
 * per-robot classes: statics per robot).
 */
public final class Pool {
    public static final class Module {
        public final String id;          // "sys" or the team package
        public final boolean perRobot;
        public final TeamClassLoaderFactory factory;
        public final TeamClassLoaderFactory.Loader loader;
        public final int index;
        Module(String id, int index, String classesUrl) {
            this.id = id;
            this.index = index;
            this.perRobot = classesUrl != null;
            if (classesUrl != null) {
                factory = new TeamClassLoaderFactory(classesUrl);
                loader = factory.createLoader(false);
            } else {
                factory = null;
                loader = null;
            }
        }
        public String toString() { return id; }
    }

    /** The engine's per-robot classes (TeamClassLoaderFactory.alwaysRedefine), slash form. */
    public static final Set<String> ALWAYS_REDEFINE = Set.of(
            "battlecode/instrumenter/inject/ObjectMethods",
            "battlecode/instrumenter/inject/InstrumentableFunctions",
            "battlecode/instrumenter/inject/System",
            "battlecode/instrumenter/inject/RobotMonitor",
            "battlecode/common/Clock");

    public final Module sys = new Module("sys", 0, null);
    public final List<Module> teams = new ArrayList<>();
    private final Map<String, Cls> classes = new HashMap<>();
    /** Whole-class substitutions for system classes: original name -> substitute class name (both slash form). */
    private final Map<String, String> substitutes = new HashMap<>();
    public final boolean debugMethods;

    public Pool(boolean debugMethods) {
        this.debugMethods = debugMethods;
        Config.getGlobalConfig().set("bc.engine.debug-methods", debugMethods ? "true" : "false");
    }

    public Module addTeam(String pkg, String classesUrl) {
        Module m = new Module(pkg, teams.size() + 1, classesUrl);
        teams.add(m);
        return m;
    }

    public void substitute(String original, String with) { substitutes.put(original, with); }

    /** Method-level patches: the patch class's methods (except constructors) and new fields replace the target's. */
    private final Map<String, List<String>> patches = new HashMap<>();
    public void patch(String target, String patchClass) { patches.computeIfAbsent(target, k -> new ArrayList<>()).add(patchClass); }

    public Collection<Cls> all() { return classes.values(); }

    /** The module a reference to {@code name} from code in {@code from} lands in. */
    public Module moduleOf(Module from, String name) {
        if (!from.perRobot) return sys;
        if (classes.containsKey(from.id + ":" + name) && classes.get(from.id + ":" + name).synthetic) return from;
        if (from.factory.hasTeamClass(name) || name.startsWith("instrumented/") || ALWAYS_REDEFINE.contains(name))
            return from;
        return sys;
    }

    /** Resolve a class reference made by code in module {@code from}. */
    public Cls ref(Module from, String name) {
        return get(moduleOf(from, name), name);
    }

    public Cls get(Module m, String name) {
        if (name.startsWith("[")) throw new IllegalArgumentException("array class " + name);
        String key = m.id + ":" + name;
        Cls c = classes.get(key);
        if (c != null) return c;
        ClassNode cn = load(m, name);
        c = new Cls(this, m, name, cn);
        classes.put(key, c);
        return c;
    }

    /** A class generated by the translator (lambdas, indy helpers), in module m. */
    public Cls addSynthetic(Module m, ClassNode cn) {
        String key = m.id + ":" + cn.name;
        if (classes.containsKey(key)) throw new TranslateException("duplicate synthetic " + key);
        Cls c = new Cls(this, m, cn.name, cn, true);
        classes.put(key, c);
        return c;
    }

    public Cls find(Module m, String name) { return classes.get(m.id + ":" + name); }

    private ClassNode load(Module m, String name) {
        try {
            byte[] b;
            if (m.perRobot) {
                if (m.factory.hasTeamClass(name)) {
                    b = m.loader.instrument(m.factory.teamReader(name), true, debugMethods);
                } else if (name.startsWith("instrumented/")) {
                    b = m.loader.instrument(TeamClassLoaderFactory.normalReader(name), false, false);
                } else if (ALWAYS_REDEFINE.contains(name) && substitutes.containsKey(name)) {
                    b = Rename.rename(resource(substitutes.get(name)), renames(substitutes.get(name), name));
                } else if (ALWAYS_REDEFINE.contains(name)) {
                    ClassReader cr = TeamClassLoaderFactory.normalReader(name);
                    ClassWriter cw = new ClassWriter(cr, ClassWriter.COMPUTE_MAXS);
                    cr.accept(cw, 0);
                    b = cw.toByteArray();
                } else {
                    throw new IllegalStateException("not a team class: " + name);
                }
            } else {
                String src = substitutes.getOrDefault(name, name);
                b = resource(src);
                if (!src.equals(name) || name.startsWith("bcx/subst/")) b = Rename.rename(b, renames(src, name));
            }
            ClassNode cn = new ClassNode();
            new ClassReader(b).accept(cn, 0);
            if (!cn.name.equals(name)) throw new IllegalStateException("class " + name + " defines " + cn.name);
            if (!m.perRobot || ALWAYS_REDEFINE.contains(name)) applyPatches(cn);
            if (completes.contains(name)) complete(cn);
            return cn;
        } catch (Exception e) {
            if (e instanceof battlecode.instrumenter.InstrumentationException && m.perRobot && m.factory.hasTeamClass(name))
                throw new TeamClassRefused(name, "loading " + m + ":" + name + ": " + e, e);
            throw new TranslateException("loading " + m + ":" + name + ": " + e, e);
        }
    }

    private void applyPatches(ClassNode cn) throws Exception {
        List<String> ps = patches.get(cn.name);
        if (ps == null) return;
        for (String p : ps) {
            ClassNode pn = new ClassNode();
            new ClassReader(Rename.rename(resource(p), renames(p, cn.name))).accept(pn, 0);
            for (MethodNode pm : pn.methods) {
                if (pm.name.equals("<init>") || isOrig(pm.invisibleAnnotations)) continue;
                // a fast path: an @Orig stub NAME$orig with the same descriptor keeps the target's method under that name
                boolean keep = false;
                for (MethodNode s : pn.methods)
                    if (s.name.equals(pm.name + "$orig") && s.desc.equals(pm.desc) && isOrig(s.invisibleAnnotations)) keep = true;
                if (keep) {
                    for (MethodNode x : cn.methods) if (x.name.equals(pm.name) && x.desc.equals(pm.desc)) x.name = pm.name + "$orig";
                } else cn.methods.removeIf(x -> x.name.equals(pm.name) && x.desc.equals(pm.desc));
                cn.methods.add(pm);
            }
            for (FieldNode pf : pn.fields) {
                if (isOrig(pf.invisibleAnnotations)) continue;
                boolean has = false;
                for (FieldNode f : cn.fields) if (f.name.equals(pf.name)) { has = true; break; }
                if (!has) cn.fields.add(pf);
            }
        }
    }

    /** Every substitute's name maps to its target, and this class's name to {@code to}. */
    private Map<String, String> renames(String from, String to) {
        Map<String, String> m = new HashMap<>();
        for (Map.Entry<String, String> e : substitutes.entrySet()) m.put(e.getValue(), e.getKey());
        // a patch class names its target, so one patch can call the methods another adds
        for (Map.Entry<String, List<String>> e : patches.entrySet()) for (String p : e.getValue()) m.put(p, e.getKey());
        m.put(from, to);
        // a patch's nested classes stand for the target's (only their names are used)
        for (String n : List.of("Sorter", "Merger", "Node")) m.put(from + "$" + n, to + "$" + n);
        return m;
    }

    /** Abstract helper classes made concrete: missing interface methods throw, bcxNew() constructs one. */
    private final Set<String> completes = new HashSet<>();
    public void complete(String name) { completes.add(name); }

    private void complete(ClassNode cn) throws Exception {
        cn.access &= ~Opcodes.ACC_ABSTRACT;
        Set<String> have = new HashSet<>();
        for (MethodNode m : cn.methods) if ((m.access & Opcodes.ACC_ABSTRACT) == 0) have.add(m.name + m.desc);
        cn.methods.removeIf(m -> (m.access & Opcodes.ACC_ABSTRACT) != 0);
        ArrayDeque<String> todo = new ArrayDeque<>(cn.interfaces);
        Set<String> seen = new HashSet<>();
        while (!todo.isEmpty()) {
            String i = todo.poll();
            if (!seen.add(i)) continue;
            ClassNode in = new ClassNode();
            new ClassReader(resource(i)).accept(in, ClassReader.SKIP_CODE);
            todo.addAll(in.interfaces);
            for (MethodNode im : in.methods) {
                if ((im.access & Opcodes.ACC_ABSTRACT) == 0 || !have.add(im.name + im.desc)) continue;
                MethodNode st = new MethodNode(Opcodes.ACC_PUBLIC, im.name, im.desc, null, null);
                st.instructions.add(new TypeInsnNode(Opcodes.NEW, "java/lang/UnsupportedOperationException"));
                st.instructions.add(new InsnNode(Opcodes.DUP));
                st.instructions.add(new LdcInsnNode("bcx: " + i + "." + im.name + " is not implemented"));
                st.instructions.add(new MethodInsnNode(Opcodes.INVOKESPECIAL, "java/lang/UnsupportedOperationException", "<init>", "(Ljava/lang/String;)V", false));
                st.instructions.add(new InsnNode(Opcodes.ATHROW));
                st.maxStack = 3;
                st.maxLocals = (org.objectweb.asm.Type.getArgumentsAndReturnSizes(im.desc) >> 2) + 1;
                cn.methods.add(st);
            }
        }
        for (MethodNode m : cn.methods) {
            if (!m.name.equals("bcxNew")) continue;
            m.instructions.clear();
            m.tryCatchBlocks.clear();
            m.instructions.add(new TypeInsnNode(Opcodes.NEW, cn.name));
            m.instructions.add(new InsnNode(Opcodes.DUP));
            m.instructions.add(new MethodInsnNode(Opcodes.INVOKESPECIAL, cn.name, "<init>", "()V", false));
            m.instructions.add(new InsnNode(Opcodes.ARETURN));
            m.maxStack = 2;
            m.maxLocals = 0;
        }
    }

    private static boolean isOrig(List<AnnotationNode> as) {
        if (as == null) return false;
        for (AnnotationNode a : as) if (a.desc.equals("Lbcx/subst/Orig;")) return true;
        return false;
    }

    static byte[] resource(String name) throws Exception {
        try (InputStream in = Pool.class.getClassLoader().getResourceAsStream(name + ".class")) {
            if (in == null) throw new TranslateException("no class file for " + name);
            return in.readAllBytes();
        }
    }

    static boolean isStatic(int access) { return (access & Opcodes.ACC_STATIC) != 0; }
}
